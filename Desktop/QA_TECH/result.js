/* 1. 
'number' + 3 + 3
'number' + 3 → 'number3'
Оператор '+' для рядка 'number' і числа 3 виконує конкатенацію.
'number3' + 3 -> 'number33'
*/
console.log('number' + 3 + 3); // -> 'number33'

/* 2. 
null + 3
null -> 0 при математичних операціях.
0 + 3 = 3 
*/
console.log(null + 3); // -> 3

/* 3. 
5 && "qwerty"
Логічний оператор && повертає перше false-значення або останнє значення, якщо всі true.
5 — true, повертається "qwerty"
*/
console.log(5 && "qwerty"); // -> "qwerty"

/* 4. 
+'40' + +'2' + "hillel" 
Унарний '+' перетворює рядок на число
+'40' = 40, +'2' = 2, 40 + 2 = 42
42 + "hillel" → "42hillel"
*/
console.log(+'40' + +'2' + "hillel"); // -> "42hillel"

/* 5.
'10' - 5 === 6
'10' - 5 -> 10 - 5 = 5 Рядок '10' приводиться до числа 10 при відніманні.
5 === 6 -> false
*/
console.log('10' - 5 === 6); // -> false

/* 6.
true + false
1 + 0 = 1 
*/
console.log(true + false); // -> 1

/* 7. 
'4px' - 3
'4px' -> NaN; Рядок '4px' не є числом, тому при відніманні приводиться до NaN.
NaN - 3 = NaN; (будь-яка арифметична операція з NaN дає NaN)
*/
console.log('4px' - 3); // -> NaN

/* 8. 
'4' - 3
'4' -> 4 рядок '4' приводиться до числа 4
4 - 3 = 1
*/
console.log('4' - 3); // -> 1

/* 9. 
'6' + 3 ** 0
3 ** 0 = 1 (будь-яке число в 0-му степені дорівнює 1)
'6' + 1 -> "61" (число 1 приводиться до рядка при конкатенації)
*/
console.log('6' + 3 ** 0); // -> "61"

/* 10. 
12 / '6' Рядок '6' приводиться до числа 6 при діленні
'6' -> 6
12 / 6 = 2
*/
console.log(12 / '6'); // -> 2

/* 11. 
'10' + (5 === 6)
5 === 6 -> false
'10' + false -> "10false" (false приводиться до рядка при конкатенації)
*/
console.log('10' + (5 === 6)); // -> "10false"

/* 12.
null == ''
false (null лише дорівнює undefined)
*/
console.log(null == ''); // -> false

/* 13.
3 ** (9 / 3); (спочатку виконується ділення в дужках)
3 ** 3 = 27
*/
console.log(3 ** (9 / 3)); // -> 27

/* 14. 
!!'false' == !!'true' !! — подвійне заперечення, перетворює значення на булеве.
'false' (непорожній рядок) -> true;
!!'false' -> true;
'true' (непорожній рядок) -> true; 
!!'true' -> true;
true == true -> true.
*/
console.log(!!'false' == !!'true'); // -> true

/* 15.
0 || '0' && 1
'0' && 1 -> 1; Оператор && має вищий пріоритет, ніж ||
'0' (непорожній рядок) -> true, 1 -> true.
'0' && 1 повертає останнє значення -> 1.
0 || 1 -> 1; (0 є false, тому || повертає 1, яке є true).
*/
console.log(0 || '0' && 1); // -> 1

/* 16.
(+null == false) < 1 
+null -> 0, (унарний + перетворює null на число 0);
false -> 0;
0 == 0 -> true
true < 1 -> false
*/
console.log((+null == false) < 1); // -> false

/* 17.
false && true || true (&& має вищий пріоритет, ніж ||)
false && true -> false; (обидва мають бути істинні)
false || true -> true; (достатньо, щоб хоч одне було істинне)
*/
console.log(false && true || true); // -> true

/* 18. 
false && (false || true) дужки мають найвищий пріоритет
false || true -> true (достатньо, щоб хоч одне було істинне)
false && true -> false (обидва мають бути істинні)
*/
console.log(false && (false || true)); // -> false

/* 19. 
(+null == false) < 1 ** 5
+null -> 0; null перетворюється на число
false -> 0; false приводиться до 0 
0 == 0 -> true;
1 ** 5 = 1; 
true < 1 -> 1 < 1 -> false
*/
console.log((+null == false) < 1 ** 5); // -> false
